package openwrt

import (
	"errors"
	"fmt"
	"os"
	"slices"
	"strings"
	"testing"
)

const (
	// The line setting the default conf-dir in /etc/init.d/dnsmasq.
	initScript2305 = "\tconfig_get dnsmasqconfdir \"$cfg\" confdir \"/tmp/dnsmasq.d\"\n"
	initScript2410 = "\t# Create a dnsmasq.d dir for each instance\n\tconfig_get dnsmasqconfdir \"$cfg\" confdir \"/tmp/dnsmasq${cfg:+.$cfg}.d\"\n"
)

func Test_dnsmasqEnv_confDir(t *testing.T) {
	const anonymous = "dhcp.cfg01411c=dnsmasq\ndhcp.cfg01411c.domainneeded='1'"
	tests := []struct {
		name string
		// show is the output of `uci -X show dhcp.@dnsmasq[0]`, empty if it fails.
		show string
		// confdir is dhcp.@dnsmasq[0].confdir, empty if unset.
		confdir string
		// generated is the configuration generated by the init script when it
		// started dnsmasq, empty if it has not.
		generated string
		// otherGenerated are the names of other files in /var/etc, with the
		// same content as generated.
		otherGenerated []string
		// confdirErr is a uci error other than the option being unset.
		confdirErr error
		// initScript is /etc/init.d/dnsmasq, empty if missing.
		initScript  string
		want        string
		wantStarted bool
		wantErr     string
	}{
		{name: "not started on 24.10+", show: anonymous, initScript: initScript2410,
			want: "/tmp/dnsmasq.cfg01411c.d"},
		{name: "not started on 24.10+, named section", show: "dhcp.main=dnsmasq", initScript: initScript2410,
			want: "/tmp/dnsmasq.main.d"},
		{name: "not started on 23.05", show: anonymous, initScript: initScript2305,
			want: "/tmp/dnsmasq.d"},
		{name: "not started, confdir option", show: anonymous, confdir: "/etc/dnsmasq.custom.d", initScript: initScript2410,
			want: "/etc/dnsmasq.custom.d"},
		{name: "not started, confdir option with extensions", show: anonymous, confdir: "/etc/dnsmasq.custom.d,*.conf", initScript: initScript2305,
			want: "/etc/dnsmasq.custom.d"},
		{name: "started on 24.10+", show: anonymous, initScript: initScript2410,
			generated: "# auto-generated config file from /etc/config/dhcp\nconf-file=/etc/dnsmasq.conf\nconf-dir=/tmp/dnsmasq.cfg01411c.d\nuser=dnsmasq\n",
			want:      "/tmp/dnsmasq.cfg01411c.d", wantStarted: true},
		{name: "started on 23.05", show: anonymous, initScript: initScript2305,
			generated: "conf-dir=/tmp/dnsmasq.d\n",
			want:      "/tmp/dnsmasq.d", wantStarted: true},
		{name: "started, generated config wins over the init script", show: anonymous, confdir: "/etc/other.d", initScript: initScript2305,
			generated: "conf-dir=/tmp/dnsmasq.cfg01411c.d,*.conf\n",
			want:      "/tmp/dnsmasq.cfg01411c.d", wantStarted: true},
		{name: "started without conf-dir", show: anonymous, confdir: "relative.d", initScript: initScript2410,
			generated:   "conf-file=/etc/dnsmasq.conf\n",
			wantStarted: true, wantErr: "without a conf-dir"},
		{name: "started with a relative conf-dir", show: anonymous, initScript: initScript2305,
			generated:   "conf-dir=relative.d\n",
			wantStarted: true, wantErr: "not an absolute path"},
		{name: "started for a single other section", show: anonymous, initScript: initScript2410,
			generated: "conf-dir=/tmp/dnsmasq.lan.d\n", otherGenerated: []string{"dnsmasq.conf.lan"},
			want: "/tmp/dnsmasq.lan.d", wantStarted: true},
		{name: "started, temporary file of the init script is ignored", show: anonymous, initScript: initScript2410,
			generated: "conf-dir=/tmp/dnsmasq.cfg01411c.d\n", otherGenerated: []string{"dnsmasq.conf.cfg01411c.1234"},
			want: "/tmp/dnsmasq.cfg01411c.d"},
		{name: "started for several other sections", show: anonymous, initScript: initScript2410,
			generated: "conf-dir=/tmp/dnsmasq.lan.d\n", otherGenerated: []string{"dnsmasq.conf.lan", "dnsmasq.conf.guest"},
			wantStarted: true, wantErr: "several sections"},
		{name: "relative confdir option", show: anonymous, confdir: "relative.d", initScript: initScript2410,
			wantErr: "not an absolute path"},
		{name: "uci fails reading the confdir option", show: anonymous, initScript: initScript2410,
			confdirErr: errors.New("uci: I/O error"),
			wantErr:    "I/O error"},
		{name: "no dnsmasq section", initScript: initScript2410,
			wantErr: "entry not found"},
		{name: "unexpected uci output", show: "dhcp.lan=dhcp", initScript: initScript2410,
			wantErr: "dnsmasq section not found"},
		{name: "no init script", show: anonymous,
			wantErr: "not exist"},
		{name: "init script with an unknown default", show: anonymous, initScript: "\tconfig_get dnsmasqconfdir \"$cfg\" confdir \"$CONFDIR/$cfg\"\n",
			wantErr: "unsupported default dnsmasq conf-dir"},
		{name: "init script without a default", show: anonymous, initScript: "#!/bin/sh /etc/rc.common\n",
			wantErr: "not found in /etc/init.d/dnsmasq"},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			var files []string
			if tt.generated != "" && tt.otherGenerated == nil {
				files = []string{"/var/etc/dnsmasq.conf.cfg01411c"}
			}
			for _, name := range tt.otherGenerated {
				files = append(files, "/var/etc/"+name)
			}
			e := dnsmasqEnv{
				uci: func(args ...string) (string, error) {
					switch strings.Join(args, " ") {
					case "-X show dhcp.@dnsmasq[0]":
						if tt.show != "" {
							return tt.show, nil
						}
					case "get dhcp.@dnsmasq[0].confdir":
						if tt.confdirErr != nil {
							return "", tt.confdirErr
						}
						if tt.confdir != "" {
							return tt.confdir, nil
						}
					}
					return "", fmt.Errorf("uci %s: %w", strings.Join(args, " "), errUCIEntryNotFound)
				},
				readFile: func(name string) ([]byte, error) {
					switch {
					case slices.Contains(files, name):
						return []byte(tt.generated), nil
					case name == "/etc/init.d/dnsmasq" && tt.initScript != "":
						return []byte(tt.initScript), nil
					}
					return nil, os.ErrNotExist
				},
				glob: func(pattern string) ([]string, error) {
					if pattern != "/var/etc/dnsmasq.conf.*" {
						t.Errorf("glob(%q)", pattern)
					}
					return files, nil
				},
			}
			got, started, err := e.confDir()
			if tt.wantErr != "" {
				if err == nil || !strings.Contains(err.Error(), tt.wantErr) {
					t.Fatalf("confDir() error = %v, want %q", err, tt.wantErr)
				}
			} else if err != nil {
				t.Fatalf("confDir() error = %v", err)
			}
			if got != tt.want {
				t.Errorf("confDir() = %q, want %q", got, tt.want)
			}
			if started != tt.wantStarted {
				t.Errorf("confDir() started = %v, want %v", started, tt.wantStarted)
			}
		})
	}
}
