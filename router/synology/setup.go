package synology

import (
	"bytes"
	"fmt"
	"net"
	"os"
	"os/exec"
	"strings"
	"time"

	"github.com/nextdns/nextdns/config"
	"github.com/nextdns/nextdns/router/internal"
)

type Router struct {
	DNSMasqPath     string
	ListenPort      string
	ClientReporting bool
	CacheEnabled    bool
	PortZeroExists  bool

	disabled bool
}

func New() (*Router, bool) {
	if b, err := exec.Command("uname", "-u").Output(); err != nil ||
		!strings.HasPrefix(string(b), "synology") {
		return nil, false
	}
	return &Router{
		DNSMasqPath: "/etc/dhcpd/dhcpd-vendor-nextdns.conf", // SRM requires two dashes
		ListenPort:  "5342",
	}, true
}

func (r *Router) String() string {
	return "synology"
}

func (r *Router) Configure(c *config.Config) error {
	if !dhcpEnabled() {
		// DHCP is disabled. Prefer :53 only when nothing else already owns it.
		if canListen53() {
			c.Listens = []string{":53"}
			r.disabled = true
			return nil
		}
		c.Listens = []string{"127.0.0.1:" + r.ListenPort}
		r.disabled = true
		return fmt.Errorf("port 53 is already in use; listening on 127.0.0.1:%s instead — disable Synology DNS Server or free :53", r.ListenPort)
	}
	c.Listens = []string{"127.0.0.1:" + r.ListenPort}
	r.ClientReporting = c.ReportClientInfo
	if cs, _ := config.ParseBytes(c.CacheSize); cs > 0 {
		r.CacheEnabled = true
		c.Listens = []string{":53"}
		if err := r.setupDNSMasq(); err != nil {
			return err
		}
		// Give dnsmasq a moment to release :53 after port=0, then verify.
		time.Sleep(200 * time.Millisecond)
		if canListen53() {
			return nil
		}
		// Fall back to forwarder mode so startup does not fail hard (#944).
		r.CacheEnabled = false
		c.Listens = []string{"127.0.0.1:" + r.ListenPort}
		if err := r.setupDNSMasq(); err != nil {
			return err
		}
		return fmt.Errorf("port 53 still in use after disabling dnsmasq DNS; falling back to 127.0.0.1:%s forwarder mode", r.ListenPort)
	}
	return nil
}

func (r *Router) Setup() error {
	if r.disabled || r.CacheEnabled {
		return nil
	}
	return r.setupDNSMasq()
}

func (r *Router) setupDNSMasq() error {
	if r.CacheEnabled {
		b, err := os.ReadFile("/etc/dhcpd/dhcpd.conf")
		r.PortZeroExists = err == nil && hasPortZero(b)
	}
	if err := internal.WriteTemplate(r.DNSMasqPath, tmpl, r, 0644); err != nil {
		return err
	}
	infoFile := strings.Replace(r.DNSMasqPath, ".conf", ".info", 1)
	if err := os.WriteFile(infoFile, []byte(`enable="yes"`), 0644); err != nil {
		return err
	}
	return restartDNSMasq()
}

func hasPortZero(b []byte) bool {
	for _, line := range bytes.Split(b, []byte{'\n'}) {
		if bytes.Equal(bytes.TrimSpace(line), []byte("port=0")) {
			return true
		}
	}
	return false
}

func dhcpEnabled() bool {
	b, err := os.ReadFile("/etc/dhcpd/dhcpd.info")
	if err != nil {
		return false
	}
	// DSM writes enable="yes" but surrounding format can vary; avoid a brittle
	// prefix-only check that mis-detects DHCP as disabled and forces :53.
	return bytes.Contains(b, []byte(`enable="yes"`))
}

// canListen53 reports whether both UDP and TCP :53 can be bound.
func canListen53() bool {
	pc, err := net.ListenPacket("udp", ":53")
	if err != nil {
		return false
	}
	_ = pc.Close()
	ln, err := net.Listen("tcp", ":53")
	if err != nil {
		return false
	}
	_ = ln.Close()
	return true
}

func (r *Router) Restore() error {
	if r.disabled {
		return nil
	}
	_ = os.Remove(r.DNSMasqPath)
	if err := restartDNSMasq(); err != nil {
		return fmt.Errorf("service restart_dnsmasq: %v", err)
	}
	return nil
}

func restartDNSMasq() error {
	// Restart dnsmasq.
	if err := exec.Command("/etc/rc.network", "nat-restart-dhcp").Run(); err != nil {
		return fmt.Errorf("/etc/rc.network nat-restart-dhcp: %v", err)
	}
	return nil
}

var tmpl = `# Configuration generated by NextDNS
{{- if .CacheEnabled}}
# DNS is handled by NextDNS
{{- if not .PortZeroExists}}
port=0
{{- end}}
{{- else}}
no-resolv
server=127.0.0.1#{{.ListenPort}}
{{- if .ClientReporting}}
add-mac
{{- end}}
add-subnet=32,128
{{- end}}
`
